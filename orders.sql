CREATE TABLE `orders` (
  `OrderID` int(6) UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `UserID` int(6) UNSIGNED NOT NULL,
  `AccID` int(6) UNSIGNED NOT NULL,
  `OrderDate` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (`UserID`) REFERENCES `member`(`UserID`) ON DELETE CASCADE,
  FOREIGN KEY (`AccID`) REFERENCES `game_accounts`(`AccID`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;